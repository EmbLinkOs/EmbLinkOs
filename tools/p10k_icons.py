#!/usr/bin/env python3
"""Generate shell/prompt/icons.c from Powerlevel10k's icon table.

third_party/powerlevel10k/internal/icons.zsh sets `icons` per
POWERLEVEL9K_MODE: a case per mode family of `NAME 'value'$s` pairs. This
keeps every mode the prompt engine offers -- flat, awesome-fontconfig,
nerdfont-v3, nerdfont-complete, ascii and the default (powerline,
compatible) -- with the \\u escapes decoded to UTF-8 and `$s` / `$q` (the icon
spacing, which POWERLEVEL9K_LEGACY_ICON_SPACING swaps) kept as the bytes
\\001 / \\002 for the engine to fill in.

    python3 tools/p10k_icons.py > shell/prompt/icons.c
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'third_party/powerlevel10k/internal/icons.zsh'
# the column each case feeds, by its label
MODES = ['flat', 'awesome-fontconfig', 'nerdfont-v3', 'nerdfont-complete', 'ascii', 'default']
LABELS = {"'flat'|'awesome-patched'": 'flat', "'awesome-fontconfig'": 'awesome-fontconfig',
          "'nerdfont-v3'": 'nerdfont-v3', "'nerdfont-complete'|'nerdfont-fontconfig'": 'nerdfont-complete',
          'ascii': 'ascii', '*': 'default'}


def decode(quoted):
    """One zsh word of quoted pieces and $s/$q into bytes."""
    out = ''
    i = 0
    while i < len(quoted):
        c = quoted[i]
        if c == "'":
            j = quoted.index("'", i + 1)
            raw = quoted[i + 1:j]
            out += re.sub(r'\\u([0-9A-Fa-f]{4})|\\U([0-9A-Fa-f]{1,8})',
                          lambda m: chr(int(m.group(1) or m.group(2), 16)), raw)
            i = j + 1
        elif quoted.startswith('$s', i):
            out += '\x01'; i += 2
        elif quoted.startswith('$q', i):
            out += '\x02'; i += 2
        elif c == ' ' or c == '\t':
            break
        else:
            raise ValueError(f'unexpected {quoted[i:]!r}')
    return out


def parse():
    text = SRC.read_text()
    table = {}
    mode = None
    for line in text.splitlines():
        s = line.strip()
        m = re.match(r"^((?:'[a-z0-9-]+'\|?)+|ascii|\*)\)$", s)
        if m and m.group(1) in LABELS:
            mode = LABELS[m.group(1)]
            continue
        if s.startswith(';;'):
            mode = None
            continue
        if mode is None:
            continue
        m = re.match(r"^([A-Z0-9_]+)\s+('.*)$", s)
        if not m:
            continue
        value = decode(m.group(2))          # stops at the first unquoted space: the comment after it
        table.setdefault(m.group(1), {})[mode] = value
    return table


def c_string(s):
    out = '"'
    for b in s.encode('utf-8'):
        if b == 0x22 or b == 0x5c:
            out += '\\' + chr(b)
        elif 0x20 <= b < 0x7f:
            out += chr(b)
        else:
            out += f'\\{b:03o}'
    return out + '"'


def main():
    table = parse()
    if 'LEFT_SEGMENT_SEPARATOR' not in table or len(table) < 100:
        sys.exit('p10k_icons: icons.zsh did not parse as expected')
    print('/* GENERATED by tools/p10k_icons.py from third_party/powerlevel10k/internal/icons.zsh\n'
          ' * (Powerlevel10k, MIT licence). Do not edit; regenerate. */')
    print('#include "prompt/icons.h"\n')
    print('const char *const p10k_icon_modes[P10K_ICON_MODES] = {' + ', '.join(c_string(m) for m in MODES) + '};\n')
    print('const struct p10k_icon p10k_icons[] = {')
    for name in sorted(table):
        row = table[name]
        cells = ', '.join(c_string(row[m]) if m in row else 'NULL' for m in MODES)
        print(f'    {{ {c_string(name)}, {{ {cells} }} }},')
    print('};')
    print(f'const unsigned p10k_icon_count = {len(table)};')


if __name__ == '__main__':
    main()
