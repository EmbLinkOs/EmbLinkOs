/* httpd.c -- an HTTP server that serves the OS's own filesystem.
 *
 * The networking stack has been finished for a while and had nothing standing
 * on it: seven programs in user/bin/ each prove one API call, and the previous
 * version of this file bound a port and returned a fixed string. This is the
 * first thing on the machine that is a SERVICE -- point a browser on the host
 * at the forwarded port and you are reading EMBKFS through our own virtio-net,
 * IPv4, TCP and socket layer, with directory listings and correct content
 * types.
 *
 * It serves one connection at a time, deliberately. A fork-per-connection
 * server would make a bigger claim about the process model than is currently
 * true, and a select() loop would be a concurrency story competing for
 * attention with the protocol story. Serial is honest, and for a machine
 * serving its own filesystem to one person it is also correct.
 *
 * The structure lives in user/httpd/: http.c (the protocol), mime.c (content
 * types), serve.c (which files a URL may reach). This file is the socket and
 * the loop and nothing else.
 *
 * usage: httpd [port] [count] [bodysz]
 *          port    default 8080
 *          count   connections to serve; 0 = forever (default 1)
 *          bodysz  >0 -- synthetic-body mode, kept for the TCP windowing
 *                  witness (`test httpdbig`): serve that many generated bytes
 *                  instead of a file, because that test measures the SENDER
 *                  rather than the server.
 * env:   HTTPD_ROOT  document root (default "/")
 * exit:  0 served; 2 socket  3 bind  4 listen  5 accept
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <errno.h>

#include "embk.h"
#include "embk_socket.h"
#include "http.h"
#include "serve.h"

static void log_req(const char *method, const char *path, int status, const char *note) {
    printf("httpd: %-4s %-40s %d%s%s\n", method, path, status,
           note ? "  " : "", note ? note : "");
}

/* Read until the end of the request head (CRLFCRLF) or the buffer fills. A
 * server that assumes the whole head arrives in one segment works on loopback
 * and fails on a real network, where a client is free to send it a byte at a
 * time. */
static long read_head(int fd, char *buf, size_t cap) {
    size_t n = 0;
    while (n + 1 < cap) {
        long r = recv(fd, buf + n, cap - 1 - n, 0);
        if (r <= 0) break;
        n += (size_t)r;
        buf[n] = 0;
        if (n >= 4 && strstr(buf, "\r\n\r\n")) break;
        if (strstr(buf, "\n\n")) break;          /* tolerate bare-LF clients */
    }
    return (long)n;
}

int main(int argc, char **argv)
{
    int port   = (argc > 1) ? atoi(argv[1]) : 8080;
    int count  = (argc > 2) ? atoi(argv[2]) : 1;
    int bodysz = (argc > 3) ? atoi(argv[3]) : 0;

    const char *root = getenv("HTTPD_ROOT");
    if (!root || root[0] != '/') root = "/";

    int lfd = socket(AF_INET, SOCK_STREAM, 0);
    if (lfd < 0) { printf("httpd: socket failed (%d)\n", lfd); return 2; }

    struct sockaddr_in sa;
    memset(&sa, 0, sizeof sa);
    sa.sin_family = AF_INET;
    sa.sin_port   = htons((unsigned short)port);
    sa.sin_addr.s_addr = INADDR_ANY;
    if (bind(lfd, (struct sockaddr *)&sa, sizeof sa) != 0) { printf("httpd: bind failed\n"); return 3; }
    if (listen(lfd, 4) != 0) { printf("httpd: listen failed\n"); return 4; }

    if (bodysz > 0) printf("httpd: :%d serving %d synthetic bytes\n", port, bodysz);
    else            printf("httpd: :%d serving %s\n", port, root);

    for (int i = 0; count == 0 || i < count; i++) {
        /* accept() has a ~3s DEADLINE in the stack (NET_TMO_TICKS) and reports
         * the expiry as an error. For a client that is a timeout; for a SERVER
         * it is just "nobody has knocked yet", and treating it as fatal makes
         * the process exit the instant it is ready to work -- which is exactly
         * what it did the first time this ran. So: keep waiting. A genuinely
         * broken listener fails differently (EBADF) and is still fatal. */
        int cfd;
        for (;;) {
            cfd = accept(lfd, 0, 0);
            if (cfd >= 0) break;
            if (cfd != -EIO) { printf("httpd: accept failed (%d)\n", cfd); return 5; }
        }

        static char head[8192];
        long n = read_head(cfd, head, sizeof head);
        if (n <= 0) { close(cfd); continue; }

        struct http_req req;
        int bad = http_parse(head, (size_t)n, &req);
        if (bad) {
            http_error(cfd, bad);
            log_req("?", "-", bad, "malformed");
            close(cfd);
            continue;
        }

        int status;
        if (bodysz > 0) {
            /* the windowing witness: ONE large write, which net_tcp_send
             * pipelines across the peer's window instead of one segment per
             * round trip */
            static char big[65536];
            int len = bodysz > (int)sizeof big ? (int)sizeof big : bodysz;
            for (int k = 0; k < len; k++) big[k] = (char)('A' + (k % 26));
            http_write_head(cfd, 200, "application/octet-stream", len);
            send(cfd, big, (size_t)len, 0);
            status = 200;
        } else {
            status = serve_request(cfd, &req, root);
        }
        log_req(req.method, req.path, status, 0);
        close(cfd);
    }

    close(lfd);
    printf("httpd: done\n");
    return 0;
}
