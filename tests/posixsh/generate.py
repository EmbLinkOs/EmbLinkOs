#!/usr/bin/env python3
"""Share observable shell-language cases between host and native acceptance."""
import json,sys
from pathlib import Path
root=Path(__file__).parent
cases=json.loads((root/'cases.json').read_text())
quote=lambda value:'NULL' if value is None else json.dumps(value,ensure_ascii=True)
text='/* Generated by tests/posixsh/generate.py; edit cases.json. */\n'
text+='struct shell_case {const char *name,*script,*output;int status;const char *option;};\n'
text+='static const struct shell_case shell_cases[]={\n'
for c in cases:text+=' {'+','.join([quote(c['name']),quote(c['script']),quote(c['stdout']),str(c['status']),quote(c['option'])])+'},\n'
text+='};\n'
p=root/'cases.h'
if '--check' in sys.argv:
 assert p.read_text()==text,'Regenerate tests/posixsh/cases.h'
else:p.write_text(text)
