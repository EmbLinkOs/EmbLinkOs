#!/usr/bin/env python3
"""Regenerate independent fixtures: Python hashlib/hmac + cryptography AES.

Run explicitly when changing wire formats. The normal C tests use the checked
in header and do not require Python or cryptography at build time.
"""
import hashlib
import hmac
from pathlib import Path
from cryptography.hazmat.primitives.keywrap import aes_key_wrap
from cryptography.hazmat.primitives.ciphers.aead import AESCCM

sta = bytes.fromhex("001122334455")
ap = bytes.fromhex("aabbccddeefe")
pmk = hashlib.pbkdf2_hmac("sha1", b"password", b"IEEE", 4096, 32)
sn = bytes(range(32))
an = bytes(range(32, 64))
seed = min(sta, ap) + max(sta, ap) + min(sn, an) + max(sn, an)
ptk = b"".join(hmac.digest(pmk, b"Pairwise key expansion\0" + seed + bytes([i]), "sha1")
               for i in range(3))[:48]
rsn = bytes.fromhex("30140100000fac040100000fac040100000fac020000")
gtk = bytes(range(0x80, 0x90))


def eapol(info, replay, nonce=bytes(32), data=b"", rsc=0, keylen=16):
    b = bytearray(99 + len(data))
    b[:4] = bytes([2, 3]) + (len(b) - 4).to_bytes(2, "big")
    b[4] = 2
    b[5:7] = info.to_bytes(2, "big")
    b[7:9] = keylen.to_bytes(2, "big")
    b[9:17] = replay.to_bytes(8, "big")
    b[17:49] = nonce
    b[65:73] = rsc.to_bytes(8, "little")
    b[97:99] = len(data).to_bytes(2, "big")
    b[99:] = data
    if info & 0x100:
        b[81:97] = hmac.digest(ptk[:16], b, "sha1")[:16]
    return bytes(b)


def keydata(rsn_ie, key, kid):
    data = rsn_ie + bytes.fromhex("dd16000fac01") + bytes([kid, 0]) + key
    if len(data) % 8:
        data += b"\xdd" + bytes((-len(data) - 1) % 8)
    return aes_key_wrap(ptk[16:32], data)


fixtures = dict(
    pmk=pmk, ptk=ptk, gtk=gtk, sta=sta, ap=ap, rsn=rsn,
    m1=eapol(0x008a, 1, an),
    m2=eapol(0x010a, 1, sn, rsn, keylen=0),
    m3=eapol(0x13ca, 2, an, keydata(rsn, gtk, 1), rsc=7),
    m4=eapol(0x030a, 2, keylen=0),
    group_m1=eapol(0x1382, 3, data=keydata(b"", bytes(range(0x90, 0xa0)), 2), rsc=9),
    group_m2=eapol(0x0302, 3, keylen=0),
    group_same_gtk_m1=eapol(0x1382, 4, data=keydata(b"", gtk, 3), rsc=1),
    bad_rsn_m3=eapol(0x13ca, 2, an, keydata(rsn[:-2] + b"\x80\x00", gtk, 1)),
    no_gtk_m3=eapol(0x13ca, 2, an, aes_key_wrap(ptk[16:32], rsn + b"\xdd\0")),
)
for qos in (False, True):
    # AP->STA infrastructure frame. CCMP authenticates masked 802.11 fields;
    # retries and sequence numbers may change without invalidating the tag.
    hdr = bytes([0x88 if qos else 0x08, 0x42, 0, 0]) + sta + ap + sta + b"\x30\x12"
    if qos:
        hdr += b"\x05\x00"
    payload = bytes.fromhex("aaaa030000000800") + bytes(range(40))
    pn = 0x060504030201
    aad = bytes([hdr[0] & 0x8f, hdr[1] & 0xc7]) + hdr[4:22] + bytes([hdr[22] & 15, 0])
    if qos:
        aad += b"\x05\0"
    nonce = bytes([5 if qos else 0]) + ap + pn.to_bytes(6, "big")
    encrypted = AESCCM(ptk[32:48], tag_length=8).encrypt(nonce, payload, aad)
    ccmp = bytes.fromhex("0102002003040506")
    fixtures["ccmp_qos" if qos else "ccmp"] = hdr + ccmp + encrypted
    plainhdr = bytearray(hdr)
    plainhdr[1] &= ~0x40
    fixtures["plain_qos" if qos else "plain"] = bytes(plainhdr) + payload

lines = ["/* Generated by wifi_vectors.py using independent Python crypto. */"]
for name, data in fixtures.items():
    lines.append(f"static const unsigned char vector_{name}[] = {{")
    for i in range(0, len(data), 12):
        lines.append("    " + ",".join(f"0x{x:02x}" for x in data[i:i+12]) + ",")
    lines.append("};")
Path(__file__).with_name("wifi_vectors.h").write_text("\n".join(lines) + "\n")
